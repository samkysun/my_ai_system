# -*- coding: utf-8 -*-
"""独立页：属性融合预测"""
import streamlit as st

import lab_page


def render(df_data, loader):
    st.markdown("## 🧬 属性融合预测")
    st.caption("十二属性联动：逐个属性给出推荐值（生肖/尾数/3余/合数…），"
               "再交叉叠加出最终号码；支持定时回测与人工剔除验证。")

    with st.expander("📘 功能说明（这套系统在做什么）", expanded=False):
        st.markdown("""
**一句话**：把号码拆成十几种「属性」，每个属性各自看历史、给推荐，
再把所有推荐交叉叠加，得出概率最高的号码。

**核心逻辑**
1. 选一个球位与目标属性（生肖 / 尾数 / 3模 / 数字合 / 四宝 / 物象 /
   方位 / 生肖五行 / 波色 / 波单双 / 门数 / 段数）。
2. 每个属性独立做「联动」：取最近 N 期该属性的取值排列，
   去历史找完全相同的排列，统计它们的下一期开出什么。
3. 每个属性得出自己的推荐值（如生肖推 3 个、尾数推 5 个，可分别设置）。
4. 交叉叠加两种口径：
   - **联合概率**：每个号码 = 各属性概率相乘，取最高的 N 个（推荐）
   - **投票叠加**：按被多少个属性推荐排序
5. 分析包：把全部推荐与合计打包成 JSON，供后续「系统大总结」使用。

**已验证的数据（2000 期回测）**
- 联合概率法取 5 个号：命中 45.7%（随机 16.7%）
- 投票叠加取 5 个号：36.0%
- 人工剔除 3 套属性后取 3 个号：剔除全对时 79%，错 1 套时 47%
""")

    with st.expander("📗 操作说明（一步一步怎么点）", expanded=False):
        st.markdown("""
**第一步：选目标**
- 目标球位：第 1 球 ~ 第 6 球
- 目标属性：结果会用这个属性表达（选生肖就推生肖）
- 预测期号：选最新一期 = 预测下一期；选历史期 = 回测那一期

**第二步：设联动**
- 联动行数：1 行最稳（2 行以上匹配期会骤减）
- 基准球位：默认第 1 球即可
- 参与融合的属性：建议全选（实测筛选无提升）

**第三步：看推荐**
- 每个属性一张表：属性值 / 推荐个数 / 得分 / 对应号码
- 下方有「实际：XXXX 期开 XX（生肖：X）→ 测中/未中」

**第四步：多属性叠加**
- 勾选要逐个测的属性
- 每个属性单独设推荐个数（生肖 3、尾数 5、3模 2…）
- 选最终号码生成方式（联合概率 / 投票叠加）
- 点「▶ 生成叠加报告」，得到最终号码 + 是否测中

**第五步：人工剔除（可选，效果最好）**
- 在多维分析里判断哪几套属性本期会失手
- 到「⑤ 勾选不中属性 → 杀号」勾上
- 点「计算剩余号码」，系统杀掉它们覆盖的号
- 剩余号码按联合概率排序，取前 1~5 个
- 页面会显示「剔除准确率」，可事后核对你的判断

**第六步：回测**
- 设回测起止期，点「▶ 回测这套推荐」
- 看属性命中率、最终号码命中率、逐期明细

**第七步：分析包**
- 点「📥 下载分析包 JSON」保存
- 或「📨 送入汇总看板」交给系统做总结
""")

    lab_page._exp_attr_fusion(loader)
